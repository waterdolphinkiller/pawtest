import fs from 'node:fs';
import path from 'node:path';

/**
 * Auto-Scaffolds ready-to-commit 2026 AI Agent Readiness protocol files directly
 * into a target directory based on actual PawTest audit findings (`--apply-scaffolds <dir>`).
 * Includes intelligent DOM-form-aware W3C WebMCP tool schema generation.
 */

function writeIfMissing(filePath, content, force = false) {
  if (fs.existsSync(filePath) && !force) {
    return { path: filePath, status: 'skipped-exists' };
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, 'utf8');
  return { path: filePath, status: 'created' };
}

export function applyFixScaffolds(report, targetDir, { force = false } = {}) {
  const outDir = path.resolve(targetDir);
  const allFindings = new Set(
    (report?.cats || []).flatMap((c) => (c.findings || []).map((f) => f.id))
  );
  const host = (() => {
    try { return new URL(report.targetUrl).host; } catch { return 'your-site.com'; }
  })();
  const origin = (() => {
    try { return new URL(report.targetUrl).origin; } catch { return `https://${host}`; }
  })();

  const generated = [];

  if (allFindings.has('robocat-missing-llms-txt')) {
    generated.push(
      writeIfMissing(
        path.join(outDir, 'llms.txt'),
        `# ${host}\n\n> Concise Markdown index for AI search engines and autonomous agents (llms.txt v2).\n\n## Core Pages\n- [Home](${origin}/index.md): Primary landing overview\n- [Documentation](${origin}/docs.md): Guides & API reference\n- [Pricing](${origin}/pricing.md): Plans & product catalog\n\n## Agent Protocols\n- UCP Manifest: ${origin}/.well-known/ucp\n- A2A Agent Card: ${origin}/.well-known/agent-card.json\n`,
        force
      )
    );
  }

  if (
    allFindings.has('robocat-live-ai-agents-blocked') ||
    allFindings.has('robocat-content-signal-blocks-ai-input') ||
    allFindings.has('robocat-x-robots-noai')
  ) {
    generated.push(
      writeIfMissing(
        path.join(outDir, 'robots.txt'),
        `# Generated by PawTest — blocks model training while allowing live AI search & user agents\nUser-agent: *\nContent-Signal: search=yes, ai-input=yes, ai-train=no\nAllow: /\n\nUser-agent: OAI-SearchBot\nAllow: /\n\nUser-agent: ChatGPT-User\nAllow: /\n\nUser-agent: Claude-User\nAllow: /\n\nUser-agent: Perplexity-User\nAllow: /\n\nUser-agent: GPTBot\nDisallow: /\n`,
        force
      )
    );
  }

  if (allFindings.has('lucky-missing-ucp') || allFindings.has('lucky-invalid-wellknown-schema')) {
    generated.push(
      writeIfMissing(
        path.join(outDir, '.well-known', 'ucp'),
        JSON.stringify(
          {
            protocol: 'ucp',
            version: '2026-01',
            merchant: { name: host, url: origin },
            capabilities: ['catalog.read', 'checkout.confirm_required', 'web_bot_auth.rfc9421'],
            endpoints: { docs: '/llms.txt' }
          },
          null,
          2
        ) + '\n',
        force
      )
    );
    generated.push(
      writeIfMissing(
        path.join(outDir, '.well-known', 'agent-card.json'),
        JSON.stringify(
          {
            name: `${host} Agent`,
            version: '1.0.0',
            url: origin,
            capabilities: { streaming: false },
            skills: [{ id: 'browse_catalog', name: 'Browse Public Content', description: `Read public pages on ${host}` }]
          },
          null,
          2
        ) + '\n',
        force
      )
    );
  }

  if (allFindings.has('musebot-no-webmcp')) {
    const muse = (report?.cats || []).find((c) => c.catId === 'musebot');
    const forms =
      Array.isArray(muse?.metrics?.detectedForms) && muse.metrics.detectedForms.length > 0
        ? muse.metrics.detectedForms
        : [
            {
              id: 'search_site',
              label: `Search ${host}`,
              fields: [{ name: 'query', type: 'string', required: true, description: 'Search keywords' }]
            }
          ];

    const toolBlocks = forms
      .map((f) => {
        const toolName = String(f.id || 'submit_form')
          .toLowerCase()
          .replace(/[^a-z0-9_]+/g, '_');
        const props = {};
        const req = [];
        for (const fld of f.fields) {
          props[fld.name] = { type: fld.type || 'string', description: fld.description || fld.name };
          if (fld.required) req.push(fld.name);
        }
        const schemaJson = JSON.stringify({ type: 'object', properties: props, required: req }, null, 2)
          .split('\n')
          .join('\n    ');
        return [
          '  document.modelContext.registerTool({',
          `    name: ${JSON.stringify(toolName)},`,
          `    description: ${JSON.stringify(`Invoke "${f.label}" form on ${host}`)},`,
          `    inputSchema: ${schemaJson},`,
          '    async execute(args) {',
          `      return { ok: true, tool: ${JSON.stringify(toolName)}, received: args };`,
          '    }',
          '  });'
        ].join('\n');
      })
      .join('\n\n');

    const snippet = [
      '// W3C WebMCP (document.modelContext) auto-inferred from live DOM forms by PawTest',
      "if (typeof document !== 'undefined' && document.modelContext && typeof document.modelContext.registerTool === 'function') {",
      toolBlocks,
      '}',
      ''
    ].join('\n');

    generated.push(writeIfMissing(path.join(outDir, 'webmcp-register.js'), snippet, force));
  }

  return generated;
}
